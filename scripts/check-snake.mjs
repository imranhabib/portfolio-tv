import assert from 'node:assert/strict';
import { createSnakeGame, createSnakeChannel } from '../src/snake.js';

const game = createSnakeGame(() => 0);
game.turn(-1, 0);
game.step();
assert.deepEqual(game.body[0], [10, 10], 'Immediate reversal must be ignored');
game.food = [11, 10];
game.step();
assert.equal(game.body.length, 4);
assert.equal(game.score, 1);
assert.ok(!game.body.some(cell => String(cell) === String(game.food)), 'Food must spawn in an empty cell');
game.turn(0, -1);
game.turn(-1, 0);
game.step();
assert.deepEqual(game.body[0], [11, 9]);
game.step();
assert.deepEqual(game.body[0], [10, 9], 'Rapid turns should apply on separate steps');
game.reset();
for (let n = 0; n < 11; n++) game.step();
assert.equal(game.ended, true, 'Walls must end the game');
game.reset();
game.body = [[2, 2], [2, 3], [3, 3], [3, 2], [3, 1]];
game.step();
assert.equal(game.ended, true, 'Moving into the body must end the game');
game.reset();
game.body = [[2, 2], [2, 3], [3, 3], [3, 2]];
game.step();
assert.equal(game.ended, false, 'Moving into the vacated tail is allowed');
game.reset();
game.body = Array.from({ length: 400 }, (_, n) => [n % 20, Math.floor(n / 20)]).filter(([x, y]) => x !== 1 || y !== 0);
game.food = [1, 0];
game.step();
assert.equal(game.body.length, 400);
assert.equal(game.food, null, 'Filling the board must win without looping while placing food');

const originals = { window: globalThis.window, document: globalThis.document, localStorage: globalThis.localStorage, random: Math.random };
try {
  const keys = {};
  const visibility = {};
  const stored = new Map();
  globalThis.window = { addEventListener(type, fn) { keys[type] = fn; } };
  globalThis.document = { hidden: false, addEventListener(type, fn) { visibility[type] = fn; } };
  globalThis.localStorage = { getItem: key => stored.get(key), setItem: (key, value) => stored.set(key, value) };
  Math.random = () => 207.1 / 397;
  const fills = [];
  const context = { fillRect(x, y) { fills.push({ x, y, color: this.fillStyle }); }, beginPath() {}, moveTo() {}, lineTo() {}, stroke() {} };
  const nodes = new Map();
  const node = selector => {
    if (!nodes.has(selector)) nodes.set(selector, { listeners: {}, addEventListener(type, fn) { this.listeners[type] = fn; }, getContext: () => context, setPointerCapture() {} });
    return nodes.get(selector);
  };
  const channel = createSnakeChannel({ querySelector: node });
  const head = () => fills.findLast(fill => fill.color === '#bdff8d');
  channel.enter();
  node('.snake-start').listeners.click();
  channel.update(0);
  channel.update(160);
  assert.equal(head().x, 242);
  assert.equal(node('.snake-score').textContent, '001');
  assert.equal(stored.get('crt-snake-best'), '1', 'High scores should persist');
  channel.leave();
  channel.update(5000);
  channel.enter();
  assert.equal(node('.snake-message').textContent, 'PAUSED');
  assert.equal(head().x, 242, 'Returning must preserve the match');
  channel.update(9000);
  assert.equal(head().x, 242, 'Returning must wait for explicit resume');
  node('.snake-start').listeners.click();
  channel.update(10000);
  channel.update(10160);
  assert.equal(head().x, 266, 'Resume must not simulate the time spent away');
  node('canvas').listeners.pointerdown({ clientX: 100, clientY: 100, pointerId: 1 });
  node('canvas').listeners.pointermove({ clientX: 100, clientY: 60 });
  node('canvas').listeners.pointerup();
  channel.update(10320);
  assert.equal(head().y, 218, 'Swiping upward should turn the snake upward');
  globalThis.document.hidden = true;
  visibility.visibilitychange();
  assert.equal(node('.snake-message').textContent, 'PAUSED', 'Hiding the browser tab must pause the match');
  console.log('Passed: movement, food, turn queue, walls, self-collision, vacated tail, full board, touch controls, score storage, and pause/resume.');
} finally {
  globalThis.window = originals.window;
  globalThis.document = originals.document;
  globalThis.localStorage = originals.localStorage;
  Math.random = originals.random;
}
